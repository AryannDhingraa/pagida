#!/usr/bin/env python3
"""
Train Pagida's small model from test-harness results, and write
src/core/data/model.ts.

    python3 scripts/train-model.py --phish phish.jsonl --legit legit.jsonl

Each input line is one page the harness visited with the extension loaded:
{"url", "finalUrl", "title", "pw", "len", "sig": [[signal_id, weight], ...]}.

It refuses to write a model from too little real phishing. Most URLs on public
phishing lists are already dead when you visit them: a GitHub Pages 404 or a
Cloudflare "Suspected phishing" interstitial is not a phishing page, and a
model trained on those learns that "404 on github.io" means phishing. Only
pages that were still serving a login form or a lure count, and there must be
at least MIN_LIVE of them.
"""
import argparse, json, math, re, sys

MIN_LIVE = 300
DEAD = re.compile(r"not found|404|unavailable|suspected phishing|glitch|unauthori[sz]ed|\b5\d\d\b|suspended|forbidden|"
                  r"parked|for sale|error|coming soon|just a moment|deceptive site|worker threw", re.I)
FACTS = ["page:password", "page:https", "page:no-dom", "page:few-links"]
NOT_FEATURES = {"phishing_feed_url_match", "phishing_feed_host_match", "safe_browsing_match", "web_risk_match",
                "local_blocklist_match", "model_assessment"}


def live(r):
    return (r.get("sig") is not None and not str(r.get("finalUrl", "")).startswith("chrome-error")
            and (r.get("len") or 0) > 80 and not DEAD.search(r.get("title") or ""))


def is_real_phish(r):
    """Still serving the attack: a password box, or a signal that only an attack produces."""
    if not live(r):
        return False
    fired = {s for s, w in r["sig"] if w > 0}
    return (r.get("pw") or fired & {"seed_phrase_request", "clickfix_command", "fake_virus_warning",
                                                   "fake_popup_window", "document_lure", "copied_sign_in_page"})


def rows(path):
    with open(path) as f:
        return [json.loads(line) for line in f if line.strip()]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--phish", required=True)
    ap.add_argument("--legit", required=True)
    ap.add_argument("--out", default="src/core/data/model.ts")
    ap.add_argument("--min-live", type=int, default=MIN_LIVE)
    a = ap.parse_args()

    phish = [r for r in rows(a.phish) if is_real_phish(r)]
    legit = [r for r in rows(a.legit) if live(r)]
    print(f"real live phishing pages: {len(phish)}, live legitimate pages: {len(legit)}")
    if len(phish) < a.min_live or len(legit) < a.min_live:
        print(f"Not enough data to train honestly (need {a.min_live} of each). Model left unchanged.")
        return 1

    from sklearn.linear_model import LogisticRegression
    from sklearn.model_selection import cross_val_score

    names = sorted({s for r in phish + legit for s, w in r["sig"] if w != 0 and s not in NOT_FEATURES})
    feats = names + FACTS

    def vec(r):
        fired = {s for s, w in r["sig"] if w != 0}
        facts = {"page:password": bool(r.get("pw")), "page:https": str(r.get("finalUrl", "")).startswith("https:"),
                 "page:no-dom": False, "page:few-links": False}
        return [1 if (facts[f] if f.startswith("page:") else f in fired) else 0 for f in feats]

    X = [vec(r) for r in phish + legit]
    y = [1] * len(phish) + [0] * len(legit)
    clf = LogisticRegression(C=0.5, max_iter=2000, class_weight="balanced")
    auc = cross_val_score(clf, X, y, cv=5, scoring="roc_auc").mean()
    clf.fit(X, y)
    print(f"5-fold ROC AUC: {auc:.3f}")

    weights = [round(float(w), 4) for w in clf.coef_[0]]
    note = f"{len(phish)} live phishing pages and {len(legit)} legitimate pages (cross-validated AUC {auc:.2f})"
    body = ("import type { ModelWeights } from '../model.js';\n\n"
            "/** Generated by scripts/train-model.py. Do not edit by hand. */\n"
            "export const MODEL: ModelWeights = " + json.dumps({
                "features": feats, "weights": weights, "bias": round(float(clf.intercept_[0]), 4), "trainedOn": note,
            }, indent=2) + ";\n")
    with open(a.out, "w") as f:
        f.write(body)
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

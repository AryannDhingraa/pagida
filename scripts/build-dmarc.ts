/**
 * Bundles the DMARC policy of every brand domain into the extension.
 *
 * Brand domains are never looked up online from a person's browser, so their
 * policies are fetched here, at build time, and shipped as data. Re-run before
 * a release: `npm run build:dmarc`.
 *
 * A DMARC record is a public note in a domain's DNS ("_dmarc.example.com")
 * that tells mail servers what to do with mail that fails the domain's
 * signature checks: reject it, quarantine it, or let it through ("none").
 */
import { writeFileSync } from 'node:fs';
import { BRAND_DOMAINS } from '../src/core/data/brands.js';
import { parseDmarc, type DmarcPolicy } from '../src/core/dmarc.js';

async function lookup(domain: string): Promise<DmarcPolicy | undefined> {
  try {
    const res = await fetch(`https://cloudflare-dns.com/dns-query?name=_dmarc.${encodeURIComponent(domain)}&type=TXT`, {
      headers: { accept: 'application/dns-json' }, signal: AbortSignal.timeout(8000),
    });
    if (!res.ok) return undefined;
    const body = await res.json() as { Status: number; Answer?: { data: string }[] };
    if (body.Status === 3) return 'missing';
    if (body.Status !== 0) return undefined;
    return parseDmarc((body.Answer ?? []).map((a) => a.data));
  } catch { return undefined; }
}

const domains = [...BRAND_DOMAINS].sort();
const out: Record<string, DmarcPolicy> = {};
for (let i = 0; i < domains.length; i += 10) {
  const batch = domains.slice(i, i + 10);
  const got = await Promise.all(batch.map(lookup));
  batch.forEach((d, k) => { const p = got[k]; if (p) out[d] = p; });
}
// A second, slower pass for the ones that timed out or were rate limited.
for (const d of domains.filter((x) => !out[x])) {
  const p = await lookup(d);
  if (p) out[d] = p;
  await new Promise((r) => setTimeout(r, 150));
}
const counts = Object.values(out).reduce<Record<string, number>>((a, p) => ({ ...a, [p]: (a[p] ?? 0) + 1 }), {});
writeFileSync('src/core/data/dmarc.ts', `/**
 * DMARC policies of the brand domains, generated by scripts/build-dmarc.ts on
 * ${new Date().toISOString().slice(0, 10)}. Do not edit by hand. ${Object.keys(out).length} of ${domains.length} answered.
 */
import type { DmarcPolicy } from '../dmarc.js';

export const BRAND_DMARC: Readonly<Record<string, DmarcPolicy>> = ${JSON.stringify(out, null, 0)};
`);
console.log(`dmarc: ${Object.keys(out).length}/${domains.length}`, counts);
